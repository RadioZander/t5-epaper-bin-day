void gfx_clear(void)
{
    memset(epd_image, 0, sizeof(epd_image));
}

void gfx_pixel(int x, int y, bool black)
{
    if (x < 0 || x >= EPD_WIDTH || y < 0 || y >= EPD_HEIGHT) {
        return;
    }
    uint8_t *byte = &epd_image[y * EPD_ROW_BYTES + x / 8];
    uint8_t bit = 0x80 >> (x % 8);
    *byte = black ? *byte | bit : *byte & ~bit;
}

void gfx_fill_rect(int x, int y, int w, int h, bool black)
{
    for (int row = y; row < y + h; row++) {
        for (int col = x; col < x + w; col++) {
            gfx_pixel(col, row, black);
        }
    }
}

void gfx_rect(int x, int y, int w, int h, bool black)
{
    gfx_fill_rect(x, y, w, 1, black);
    gfx_fill_rect(x, y + h - 1, w, 1, black);
    gfx_fill_rect(x, y, 1, h, black);
    gfx_fill_rect(x + w - 1, y, 1, h, black);
}

static void draw_char(int x, int y, char c, int scale, bool black)
{
    if (c < 0x20 || c > 0x7E) {
        c = '?';
    }
    const uint8_t *glyph = font5x7[c - 0x20];
    for (int col = 0; col < 5; col++) {
        for (int row = 0; row < 8; row++) {
            if (glyph[col] & (1 << row)) {
                gfx_fill_rect(x + col * scale, y + row * scale, scale, scale, black);
            }
        }
    }
}

int gfx_text_width(const char *text, int scale)
{
    int n = strlen(text);
    // 5 px glyph + 1 px spacing, no trailing spacing
    return n ? (n * 6 - 1) * scale : 0;
}

void gfx_text(int x, int y, const char *text, int scale, bool black)
{
    for (; *text; text++, x += 6 * scale) {
        draw_char(x, y, *text, scale, black);
    }
}

void gfx_text_centered(int y, const char *text, int scale, bool black)
{
    gfx_text((EPD_WIDTH - gfx_text_width(text, scale)) / 2, y, text, scale, black);
}

static const gfx_glyph_t *glyph_for(const gfx_font_t *font, char c)
{
    if (c < font->first || c > font->last) {
        c = '?';
    }
    return &font->glyphs[c - font->first];
}

// From the start of the first glyph to the end of the last one's pixels
int gfx_text_font_width(const char *text, const gfx_font_t *font)
{
    int w = 0;
    for (; *text; text++) {
        const gfx_glyph_t *g = glyph_for(font, *text);
        w += text[1] ? g->advance : g->x_offset + g->width;
    }
    return w;
}

void gfx_text_font(int x, int y, const char *text, const gfx_font_t *font, bool black)
{
    int baseline = y + font->cap_height;
    for (; *text; text++) {
        const gfx_glyph_t *g = glyph_for(font, *text);
        const uint8_t *bits = font->bitmap + g->offset;
        for (int i = 0; i < g->width * g->height; i++) {
            if (bits[i / 8] & (0x80 >> (i % 8))) {
                gfx_pixel(x + g->x_offset + i % g->width, baseline + g->y_offset + i / g->width, black);
            }
        }
        x += g->advance;
    }
}

void gfx_text_font_centered(int y, const char *text, const gfx_font_t *font, bool black)
{
    gfx_text_font((EPD_WIDTH - gfx_text_font_width(text, font)) / 2, y, text, font, black);
}
